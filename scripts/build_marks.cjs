// Rebuilds dist/tech-marks.js from assets/tech/*.svg: the hero's twelve
// logos as one module instead of twelve fetches. verify fails if the two
// drift apart. Run with: node scripts/build_marks.cjs
const fs = require('node:fs');
const path = require('node:path');
const dir = path.resolve(__dirname, '../assets/tech');
const render = () => {
  const entries = fs.readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()
    .map((f) => `  ${JSON.stringify(f.slice(0, -4))}: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8').trim())},`);
  return `// Generated by scripts/build_marks.cjs from assets/tech. Do not edit.\nexport default {\n${entries.join('\n')}\n};\n`;
};
module.exports = { render };
if (require.main === module) fs.writeFileSync(path.resolve(__dirname, '../dist/tech-marks.js'), render());
